// Generates the CV PDF from the website's content:
//   1. load and validate src/content/ with the same schemas as the site
//   2. write cv/build/Xiwen_Teoh_CV.yaml (RenderCV's `cv:` input)
//   3. render it with RenderCV using the layout in cv/{design,locale,settings}.yaml
//
// Usage: node scripts/build-cv.ts [--yaml-only]
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse, stringify } from "yaml";
import type { z } from "astro/zod";
import {
  awardSchema,
  educationSchema,
  publicationSchema,
  roleSchema,
  serviceSchema,
  talkSchema,
} from "../src/content/schemas.ts";
import { buildCv } from "../src/utils/rendercv.ts";

const CONTENT = "src/content";
const OUT_YAML = "cv/build/Xiwen_Teoh_CV.yaml";
// RenderCV resolves relative output paths against the input file's folder, so
// pass absolute ones. The Typst file is required: the PDF is built from it.
const OUT_TYPST = resolve("cv/build/Xiwen_Teoh_CV.typ");
const OUT_PDF = resolve("public/Xiwen_Teoh_CV.pdf");

function parseOrExit<T>(schema: z.ZodType<T>, data: unknown, source: string) {
  const result = schema.safeParse(data);
  if (!result.success) {
    console.error(`Invalid content in ${source}:\n${result.error.message}`);
    process.exit(1);
  }
  return result.data;
}

// Markdown entries keep everything in YAML frontmatter.
function loadMarkdown<T>(dir: string, schema: z.ZodType<T>): T[] {
  return readdirSync(join(CONTENT, dir))
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => {
      const path = join(CONTENT, dir, name);
      const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(
        readFileSync(path, "utf8"),
      );
      if (!match) {
        console.error(`Missing frontmatter in ${path}`);
        process.exit(1);
      }
      return parseOrExit(schema, parse(match[1]), path);
    });
}

function loadYaml<T>(name: string, schema: z.ZodType<T>): T[] {
  const path = join(CONTENT, "cv", name);
  const entries: unknown[] = parse(readFileSync(path, "utf8")) ?? [];
  return entries.map((entry, i) =>
    parseOrExit(schema, entry, `${path} (entry ${i + 1})`),
  );
}

const cv = buildCv({
  publications: loadMarkdown("publications", publicationSchema),
  awards: loadMarkdown("awards", awardSchema),
  education: loadYaml("education.yaml", educationSchema),
  experience: loadYaml("experience.yaml", roleSchema),
  talks: loadYaml("talks.yaml", talkSchema),
  teaching: loadYaml("teaching.yaml", roleSchema),
  service: loadYaml("service.yaml", serviceSchema),
});

mkdirSync("cv/build", { recursive: true });
writeFileSync(
  OUT_YAML,
  "# Generated by scripts/build-cv.ts from src/content/. Do not edit;\n" +
    "# change the content (or its `cv:` overrides) and cv/*.yaml instead.\n" +
    stringify(cv, { lineWidth: 0 }),
);
console.log(`Wrote ${OUT_YAML}`);

if (process.argv.includes("--yaml-only")) process.exit(0);

const render = spawnSync(
  "uv",
  [
    "run",
    "--project",
    "cv",
    "--frozen",
    "rendercv",
    "render",
    OUT_YAML,
    "--design",
    "cv/design.yaml",
    "--locale-catalog",
    "cv/locale.yaml",
    "--settings",
    "cv/settings.yaml",
    "--typst-path",
    OUT_TYPST,
    "--pdf-path",
    OUT_PDF,
    "--dont-generate-markdown",
    "--dont-generate-html",
    "--dont-generate-png",
  ],
  { stdio: "inherit" },
);
if (render.error) {
  console.error(
    `Could not run uv (${render.error.message}). Install it from https://docs.astral.sh/uv/`,
  );
  process.exit(1);
}
process.exit(render.status ?? 1);
